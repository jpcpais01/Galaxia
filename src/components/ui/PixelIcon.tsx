export function PixelIcon({
  id, color, size = 16,
}: { id: string; color: string; size?: number }) {
  const ref = useRef<HTMLCanvasElement>(null);
  const rows = PIXEL_ICONS[id] ?? PIXEL_ICONS['humanoid'];

  useEffect(() => {
    const canvas = ref.current;
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    if (!ctx) return;
    ctx.clearRect(0, 0, 16, 16);
    ctx.fillStyle = color;
    for (let y = 0; y < 8; y++) {
      const row = rows[y];
      for (let x = 0; x < 8; x++) {
        if (row & (0x80 >> x)) ctx.fillRect(x * 2, y * 2, 2, 2);
      }
    }
  }, [id, color, rows]);

  return (
    <canvas
      ref={ref}
      width={16}
      height={16}
      style={{ width: size, height: size, imageRendering: 'pixelated', display: 'block', flexShrink: 0 }}
    />
  );
}
